/**
 * Embeds the built console (dist/, minus APK downloads) into the Worker as a
 * module, so the Worker serves the SPA itself. Used instead of Workers Static
 * Assets so deployment needs only the Workers Scripts API.
 *   node scripts/embed-assets.mjs            (after `vite build`)
 *   node scripts/embed-assets.mjs --if-missing  (type-checking without a build)
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const out = join(root, 'worker', 'generated', 'assets.ts');
if (process.argv.includes('--if-missing') && existsSync(out)) process.exit(0);

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.webmanifest': 'application/manifest+json',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const rel = '/' + relative(dist, p).split('\\').join('/');
    if (statSync(p).isDirectory()) {
      if (rel !== '/downloads') walk(p);
      continue;
    }
    if (name === '_headers' || name === '.nojekyll' || !TYPES[extname(name)]) continue;
    files[rel] = { type: TYPES[extname(name)], b64: readFileSync(p).toString('base64'), immutable: rel.startsWith('/assets/') };
  }
};
if (existsSync(dist)) walk(dist);
mkdirSync(join(root, 'worker', 'generated'), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/embed-assets.mjs — do not edit.\nexport const ASSETS: Record<string, { type: string; b64: string; immutable: boolean }> = ${JSON.stringify(files)};\n`,
);
console.log(`embedded ${Object.keys(files).length} files (${Math.round(JSON.stringify(files).length / 1024)} KiB) into worker/generated/assets.ts`);
